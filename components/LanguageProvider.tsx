function savedLanguage() {
  let stored: string | null = null;
  let cookie: string | undefined;
  try {
    stored = localStorage.getItem(LANGUAGE_PREFERENCE_KEY);
  } catch {
    /* Storage may be blocked. */
  }
  try {
    cookie = document.cookie
      .split(";")
      .map((part) => part.trim())
      .find((part) => part.startsWith(`${LANGUAGE_PREFERENCE_KEY}=`))
      ?.slice(LANGUAGE_PREFERENCE_KEY.length + 1);
  } catch {
    /* Cookie access may also be blocked. */
  }
  return { stored, cookie };
}

function persistLanguage(language: Language) {
  try {
    localStorage.setItem(LANGUAGE_PREFERENCE_KEY, language);
  } catch {
    /* Cookie fallback remains available. */
  }
  try {
    document.cookie =
      `${LANGUAGE_PREFERENCE_KEY}` +
      "=" +
      `${language}` +
      "; Path=/; Max-Age=" +
      `${LANGUAGE_COOKIE_MAX_AGE}` +
      "; SameSite=Lax" +
      `${window.location.protocol === "https:" ? "; Secure" : ""}`;
  } catch {
    /* localStorage remains available when cookies are blocked. */
  }
}

export function LanguageProvider({
  children,
  initialLanguage,
}: {
  children: React.ReactNode;
  initialLanguage?: Language;
}) {
  const [language, updateLanguage] = useState<Language>(initialLanguage ?? "en");
  useEffect(() => {
    const { stored, cookie } = savedLanguage();
    const selected = preferredLanguage(stored, cookie, initialLanguage, browserLanguage());
    updateLanguage(selected);
    document.documentElement.lang = selected;
    persistLanguage(selected);
  }, [initialLanguage]);
  const setLanguage = (selected: Language) => {
    if (!isLanguage(selected)) return;
    persistLanguage(selected);
    updateLanguage(selected);
    document.documentElement.lang = selected;
  };
  const value = useMemo(
    () => ({
      language,
      locale: localeMap[language],
      setLanguage,
      t: (key: TranslationKey, values?: TranslationValues) => translate(language, key, values),
      ta: (key: AdminTranslationKey, values?: TranslationValues) =>
        interpolate(adminTranslations[language][key], values),
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
